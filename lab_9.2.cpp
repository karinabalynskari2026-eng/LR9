/*
    lab_9_2.
    Варіант 1.
    Використовуючи директиви умовної компіляції, макровизначення, включення
    власних заголовних файлів та інші директиви, обчислити вираз:

            | max (x^2 + y + z, x*y*z),      0 < z < 5
        w = |
            | min (x^2 + (y + z)^2, x*y),    z <= 0, z >= 5

    Функції max(), min(), піднесення до квадрата та виведення результатів
    задані у вигляді макросів (файл macros.h).
    Значення x, y задаються користувачем. Значення z задається макросом Z:
    препроцесор на основі Z визначає, яка з двох гілок буде компілюватися.
*/

#include <stdio.h>
#include "macros.h"                 // власний заголовний файл з макросами

#ifndef Z                           // якщо Z не задано ззовні (-DZ=...)
#define Z 3                         // директива препроцесора – значення z
#endif

int main()
{
    puts("Lab 9.2. Using macros and preprocessing directive");
    float x, y;                     // змінні, які вводить користувач
    float w;                        // результат
    char ch;                        // відповідь чи продовжувати виконання програми
    do
    {
        puts("Input 2 real numbers x and y");
        scanf("%f", &x);            // введення числа x
        PRINTC(x);                  // макрос виведення числа
        scanf("%f", &y);            // введення числа y
        PRINTC(y);
        PRINTC(Z);

#if (Z > 0) && (Z < 5)              // якщо умова істинна, то обчислюємо max
        puts("0 < z < 5: w = max(x^2 + y + z, x*y*z)");
        w = MAX(SQR(x) + y + Z, x * y * Z);         // макроси max та піднесення до квадрата
#else                               // компілювати іншу частину програми, якщо z <= 0 або z >= 5
        puts("z <= 0 or z >= 5: w = min(x^2 + (y + z)^2, x*y)");
        w = MIN(SQR(x) + SQR(y + Z), x * y);        // макроси min та піднесення до квадрата
#endif                              // завершення блоку умовної компіляції

        PRINTR(w);                  // макрос виведення результату
        puts("Repeat? y/n");
        scanf(" %c", &ch);
    } while (ch == 'y');
    return 0;
}